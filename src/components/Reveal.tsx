"use client";

import { useEffect, useRef, type ReactNode } from "react";

/**
 * Fades content up once as it scrolls into view.
 *
 * Progressive enhancement: content is visible in the server HTML. It is only hidden (by CSS, under `html.js`)
 * once JavaScript runs, so no-JS visitors, crawlers and people who prefer reduced motion always see it.
 */
export function Reveal({ children, delay = 0, className = "" }: { children: ReactNode; delay?: number; className?: string }) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          el.classList.add("in");
          io.disconnect();
        }
      },
      { rootMargin: "0px 0px -80px 0px" },
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);
  return (
    <div ref={ref} className={`reveal ${className}`} style={delay ? { transitionDelay: `${delay}s` } : undefined}>
      {children}
    </div>
  );
}
